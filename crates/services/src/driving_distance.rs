//! Durable distance checkpoints from an owned logic lifetime.
//!
//! This bounded journal is local persistence policy, not a game table. Each
//! stream reports its cumulative whole metres, not a repeatable increment.
//! Its watermark and the account's distance commit atomically. Retired entries
//! fail closed rather than allowing an old retry to count twice. Whole-career
//! replacement clears the journal with the other career tables.
use crate::persistent::{Catalog, key};
use nfs_storage::{
    AccountId, Batch, Error, InventoryRepository, Op, Snapshot, Timestamp,
    tables::{Table, Value},
};

pub const TABLE: &str = "AfterhoursDrivingDistance";
pub const STATS: &str = "GameplayStatsTable";
pub const COLUMN: &str = "DistanceDriven";
pub const MAX_STREAMS: usize = 128;
const NAMESPACE: u64 = 1 << 51;
const VERSION: u32 = 0;
const IDENTITY: u32 = 1;
const METRES: u32 = 2;

/// Generated by the host before opening a stream. Keep the original identity
/// and starting generation on a retry; never derive them from client input.
/// A new logic lifetime needs a fresh identity. Account and generation scope
/// prevent a retired lifetime from reopening after a reset or journal eviction.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct Stream {
    account: AccountId,
    generation: u64,
    identity: String,
}

impl Stream {
    pub fn new(account: AccountId, generation: u64, identity: [u8; 16]) -> Result<Self, Error> {
        if generation >= NAMESPACE || identity == [0; 16] {
            return Err(Error::Invalid);
        }
        Ok(Self {
            account,
            generation,
            identity: identity.iter().map(|b| format!("{b:02x}")).collect(),
        })
    }

    fn row(&self) -> u64 {
        self.generation + 1
    }
}

fn journal(snapshot: &Snapshot) -> Result<Table, Error> {
    let Some(table) = snapshot.tables.get(&key(TABLE)) else {
        return Ok(Table {
            rows: [(0, [(VERSION, Value::Int(1))].into())].into(),
        });
    };
    if table.rows.is_empty()
        || table.rows.len() > MAX_STREAMS + 1
        || table.rows.get(&0) != Some(&[(VERSION, Value::Int(1))].into())
    {
        return Err(Error::Config);
    }
    for (&id, row) in table.rows.iter().filter(|(id, _)| **id != 0) {
        if id >= NAMESPACE || id > snapshot.generation || row.len() != 2 {
            return Err(Error::Config);
        }
        if !matches!(row.get(&METRES), Some(Value::Int(n)) if *n >= 0)
            || !matches!(row.get(&IDENTITY), Some(Value::String(s)) if s.len() == 32
                && s.bytes().all(|c| c.is_ascii_digit() || (b'a'..=b'f').contains(&c))
                && s.bytes().any(|c| c != b'0'))
        {
            return Err(Error::Config);
        }
    }
    Ok(table.clone())
}

fn watermark(table: &Table, stream: &Stream) -> Result<Option<i32>, Error> {
    let Some(row) = table.rows.get(&stream.row()) else {
        return Ok(None);
    };
    if row.get(&IDENTITY) != Some(&Value::String(stream.identity.clone())) {
        return Err(Error::Conflict);
    }
    match row.get(&METRES) {
        Some(Value::Int(n)) if *n >= 0 => Ok(Some(*n)),
        _ => Err(Error::Config),
    }
}

fn batch(snapshot: &Snapshot, ops: Vec<Op>) -> Result<Batch, Error> {
    if snapshot.generation >= NAMESPACE - 1 {
        return Err(Error::Bounds);
    }
    let batch = Batch {
        id: NAMESPACE | snapshot.generation,
        expected_generation: snapshot.generation,
        ops,
    };
    batch.validate()?;
    Ok(batch)
}

fn prepare_open(snapshot: &Snapshot, stream: &Stream) -> Result<Option<Batch>, Error> {
    let mut next = journal(snapshot)?;
    if watermark(&next, stream)?.is_some() {
        return Ok(None);
    }
    if snapshot.generation != stream.generation {
        return Err(Error::Conflict);
    }
    if next.rows.len() == MAX_STREAMS + 1 {
        let oldest = *next.rows.keys().find(|id| **id != 0).ok_or(Error::Config)?;
        next.rows.remove(&oldest);
    }
    next.rows.insert(
        stream.row(),
        [
            (IDENTITY, Value::String(stream.identity.clone())),
            (METRES, Value::Int(0)),
        ]
        .into(),
    );
    Ok(Some(batch(snapshot, vec![Op::SetTable(key(TABLE), next)])?))
}

pub fn metres(catalog: &Catalog, snapshot: &Snapshot) -> Result<i32, Error> {
    let value = catalog
        .view(snapshot)?
        .stores()
        .get(&(key(STATS), key(COLUMN)))
        .copied()
        .ok_or(Error::Config)?;
    if value < 0 {
        return Err(Error::Config);
    }
    Ok(value)
}

fn prepare(
    catalog: &Catalog,
    snapshot: &Snapshot,
    stream: &Stream,
    cumulative: i32,
) -> Result<Option<Batch>, Error> {
    if cumulative < 0 {
        return Err(Error::Invalid);
    }
    let mut next = journal(snapshot)?;
    let before = watermark(&next, stream)?.ok_or(Error::Conflict)?;
    let old = metres(catalog, snapshot)?;
    // A later checkpoint may already have won while this older job was delayed.
    if cumulative <= before {
        return Ok(None);
    }
    let value = old.checked_add(cumulative - before).ok_or(Error::Bounds)?;
    let mut stats = snapshot
        .tables
        .get(&key(STATS))
        .cloned()
        .ok_or(Error::Config)?;
    stats
        .rows
        .entry(0)
        .or_default()
        .insert(key(COLUMN), Value::Int(value));
    next.rows
        .get_mut(&stream.row())
        .ok_or(Error::Conflict)?
        .insert(METRES, Value::Int(cumulative));
    Ok(Some(batch(
        snapshot,
        vec![
            Op::SetTable(key(STATS), stats),
            Op::SetTable(key(TABLE), next),
        ],
    )?))
}

/// Opens only the specified generation. A competing unrelated commit can
/// require a fresh open request, but an ambiguous timeout must retry this one.
/// Success is verified from durable state, never merely a batch-ID receipt.
pub fn open(
    repository: &dyn InventoryRepository,
    stream: &Stream,
    now: Timestamp,
) -> Result<Snapshot, Error> {
    transact(repository, stream, now, |snapshot| {
        prepare_open(snapshot, stream)
    })
}

/// Checkpoint a cumulative stream value. Concurrent streams and unrelated
/// transactions rebase through a bounded loop; a receipt collision alone never
/// acknowledges a different stream or skips its uncommitted distance.
pub fn commit(
    repository: &dyn InventoryRepository,
    catalog: &Catalog,
    stream: &Stream,
    cumulative: i32,
    now: Timestamp,
) -> Result<Snapshot, Error> {
    transact(repository, stream, now, |snapshot| {
        prepare(catalog, snapshot, stream, cumulative)
    })
}

fn transact(
    repository: &dyn InventoryRepository,
    stream: &Stream,
    now: Timestamp,
    prepare: impl Fn(&Snapshot) -> Result<Option<Batch>, Error>,
) -> Result<Snapshot, Error> {
    for _ in 0..8 {
        let snapshot = repository.snapshot(stream.account)?;
        let Some(batch) = prepare(&snapshot)? else {
            return Ok(snapshot);
        };
        match repository.apply(stream.account, &batch, now) {
            Ok(_) | Err(Error::Conflict) => {}
            Err(error) => return Err(error),
        }
    }
    Err(Error::Conflict)
}

